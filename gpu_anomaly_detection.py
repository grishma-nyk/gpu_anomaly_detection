# --- 1. Data Simulation (More Realistic + CPU Usage) ---
def generate_gpu_data(num_samples=10000, anomaly_info=None):
    np.random.seed(42)
    time = np.arange(num_samples)

    # Temperature
    temp_base = 35 + np.random.rand(num_samples) * 5
    long_term_trend = np.zeros(num_samples)
    num_steps = 5; step_length = num_samples // num_steps
    for i in range(num_steps): long_term_trend[i*step_length:(i+1)*step_length] = np.random.uniform(0, 15)
    temp_base += long_term_trend

    # GPU Utilization
    utilization = np.zeros(num_samples)
    num_phases = 20; phase_len = num_samples // num_phases
    for i in range(num_phases):
        start_idx, end_idx = i * phase_len, (i + 1) * phase_len
        if np.random.rand() < 0.2: utilization[start_idx:end_idx] = np.random.uniform(0, 15, end_idx - start_idx)
        elif np.random.rand() < 0.5: utilization[start_idx:end_idx] = np.random.uniform(30, 70, end_idx - start_idx)
        else: utilization[start_idx:end_idx] = np.random.uniform(70, 100, end_idx - start_idx)
    utilization = np.clip(utilization + np.random.normal(0, 5, num_samples), 0, 100)

    temp_load_component = (utilization / 100) * np.random.uniform(20, 40, num_samples)
    temp = np.clip(temp_base + temp_load_component + np.random.normal(0, 3, num_samples), 30, 85)

    # Memory Utilization
    mem_util = np.zeros(num_samples)
    mem_base_factor = np.random.uniform(0.3, 0.7, num_samples)
    mem_util = utilization * mem_base_factor + np.random.normal(0, 10, num_samples)
    for _ in range(num_samples // 500):
        idx = np.random.randint(0, num_samples - 50)
        mem_util[idx:idx+np.random.randint(10,50)] += np.random.uniform(20, 40)
    mem_util = np.clip(mem_util, 5, 95)

    # Power Consumption
    power = 40 + (utilization / 100) * 200 + ((temp - 35) / 50) * 30
    power = np.clip(power + np.random.normal(0, 10, num_samples), 35, 280)

    # CPU Utilization (%)
    cpu_util = np.zeros(num_samples)
    num_cpu_phases = 15; cpu_phase_len = num_samples // num_cpu_phases
    for i in range(num_cpu_phases):
        start_idx, end_idx = i * cpu_phase_len, (i + 1) * cpu_phase_len
        base_level = np.random.uniform(10, 25) # Base OS/idle tasks
        workload_level = np.random.uniform(0, 30) # General workload component
        cpu_util[start_idx:end_idx] = base_level + workload_level
    gpu_correlation_strength = np.random.uniform(0.05, 0.3, num_samples) # CPU less directly tied to GPU than power
    cpu_util += utilization * gpu_correlation_strength
    cpu_util = np.clip(cpu_util + np.random.normal(0, 8, num_samples), 5, 90) # CPU rarely hits 100 unless specific stress

    labels = np.zeros(num_samples, dtype=int)
    df = pd.DataFrame({
        'Time': time, 'Temperature': temp, 'GPU_Utilization': utilization,
        'Memory_Utilization': mem_util, 'Power_Consumption': power,
        'CPU_Utilization': cpu_util, 'Label': labels
    })

    # Inject user-defined anomaly
    if anomaly_info:
        metric = anomaly_info['metric']
        start_time_idx = anomaly_info['start_time']
        duration_idx = anomaly_info['duration']
        severity_factor = anomaly_info['severity_factor']
        end_time_idx = start_time_idx + duration_idx
        if start_time_idx < 0: start_time_idx = 0
        if end_time_idx > num_samples: end_time_idx = num_samples
        idx_range = slice(start_time_idx, end_time_idx)

        current_cpu_vals = df.loc[idx_range, 'CPU_Utilization'].copy()

        if metric == 'Temperature':
            df.loc[idx_range, 'Temperature'] = np.clip(df.loc[idx_range, 'Temperature'] * severity_factor, 30, 95)
            if severity_factor > 1.15:
                 df.loc[idx_range, 'Power_Consumption'] = np.clip(df.loc[idx_range, 'Power_Consumption'] * 1.15, 40, 310)
                 df.loc[idx_range, 'CPU_Utilization'] = np.clip(current_cpu_vals + np.random.uniform(5,10), 5, 95)
        elif metric == 'GPU_Utilization': # severity_factor is the stuck value
            df.loc[idx_range, 'GPU_Utilization'] = np.clip(severity_factor, 0, 100)
            if severity_factor > 90:
                df.loc[idx_range, 'Temperature'] = np.clip(df.loc[idx_range, 'Temperature'] * 1.2, 30, 93)
                df.loc[idx_range, 'Power_Consumption'] = np.clip(df.loc[idx_range, 'Power_Consumption'] * 1.2, 40, 320)
                df.loc[idx_range, 'CPU_Utilization'] = np.clip(current_cpu_vals + np.random.uniform(8,15), 5, 98)
        elif metric == 'Memory_Utilization':
             df.loc[idx_range, 'Memory_Utilization'] = np.clip(df.loc[idx_range, 'Memory_Utilization'] * severity_factor, 5, 98)
             if severity_factor > 1.5 : df.loc[idx_range, 'CPU_Utilization'] = np.clip(current_cpu_vals + np.random.uniform(3,7), 5, 95)
        elif metric == 'Power_Consumption':
            df.loc[idx_range, 'Power_Consumption'] = np.clip(df.loc[idx_range, 'Power_Consumption'] * severity_factor, 40, 330)
            if severity_factor > 1.3 : df.loc[idx_range, 'CPU_Utilization'] = np.clip(current_cpu_vals + np.random.uniform(5,12), 5, 95)
        elif metric == 'CPU_Utilization': # severity_factor is the stuck value for CPU
            df.loc[idx_range, 'CPU_Utilization'] = np.clip(severity_factor, 0, 100)
            # High CPU might also slightly warm other components
            if severity_factor > 85:
                df.loc[idx_range, 'Temperature'] = np.clip(df.loc[idx_range, 'Temperature'] * 1.05, 30, 90) # Minor temp increase
        df.loc[idx_range, 'Label'] = 1


    # Add some built-in anomalies
    num_builtin_anomalies = 15
    for _ in range(num_builtin_anomalies):
        idx = np.random.randint(0, num_samples - 100)
        duration = np.random.randint(20,70)
        anomaly_type = np.random.choice(['temp_spike', 'power_surge', 'mem_leak_sim', 'gpu_stuck_low', 'cpu_spike'])
        builtin_idx_range = slice(idx, idx + duration)
        current_cpu_built_in = df.loc[builtin_idx_range, 'CPU_Utilization'].copy()

        if anomaly_type == 'temp_spike':
            df.loc[builtin_idx_range, 'Temperature'] += np.random.uniform(10,20)
            df.loc[builtin_idx_range, 'Power_Consumption'] = np.clip(df.loc[builtin_idx_range, 'Power_Consumption'] * np.random.uniform(1.1, 1.3), 40, 310)
            df.loc[builtin_idx_range, 'CPU_Utilization'] = np.clip(current_cpu_built_in + np.random.uniform(3,8), 5, 95)
        elif anomaly_type == 'power_surge':
            df.loc[builtin_idx_range, 'Power_Consumption'] = np.clip(df.loc[builtin_idx_range, 'Power_Consumption'] * np.random.uniform(1.2, 1.5), 40, 320)
            df.loc[builtin_idx_range, 'Temperature'] += np.random.uniform(3,8)
            df.loc[builtin_idx_range, 'CPU_Utilization'] = np.clip(current_cpu_built_in + np.random.uniform(5,10), 5, 98)
        elif anomaly_type == 'mem_leak_sim':
            df.loc[builtin_idx_range, 'Memory_Utilization'] = np.clip(df.loc[builtin_idx_range, 'Memory_Utilization'] + np.random.uniform(20,40), 5, 98)
        elif anomaly_type == 'gpu_stuck_low':
            df.loc[builtin_idx_range, 'GPU_Utilization'] = np.clip(df.loc[builtin_idx_range, 'GPU_Utilization'] * np.random.uniform(0.1, 0.3), 0, 20) # Stuck low
            df.loc[builtin_idx_range, 'Power_Consumption'] *= np.random.uniform(0.5, 0.8)
            df.loc[builtin_idx_range, 'Temperature'] -= np.random.uniform(5,10)
        elif anomaly_type == 'cpu_spike':
            df.loc[builtin_idx_range, 'CPU_Utilization'] = np.clip(current_cpu_built_in + np.random.uniform(30,50), 5, 99) # Significant CPU spike
            df.loc[builtin_idx_range, 'Temperature'] = np.clip(df.loc[builtin_idx_range, 'Temperature'] * 1.02, 30, 90) # Minor temp increase

        df.loc[builtin_idx_range, 'Label'] = 1

    # Final clipping
    df['Temperature'] = np.clip(df['Temperature'], 25, 98)
    df['Power_Consumption'] = np.clip(df['Power_Consumption'], 30, 330)
    df['Memory_Utilization'] = np.clip(df['Memory_Utilization'], 0, 99)
    df['CPU_Utilization'] = np.clip(df['CPU_Utilization'], 3, 99)
    df['GPU_Utilization'] = np.clip(df['GPU_Utilization'], 0, 100)
    return df

print("Data generation function defined.\n")

# --- 2. Interactive Anomaly Injection Setup ---
metric_dropdown = widgets.Dropdown(options=['Temperature', 'GPU_Utilization', 'Memory_Utilization', 'Power_Consumption', 'CPU_Utilization'], description='Metric:')
start_time_slider = widgets.IntSlider(min=0, max=9800, step=100, value=5000, description='Start Time:')
duration_slider = widgets.IntSlider(min=50, max=500, step=10, value=100, description='Duration:')
severity_slider = widgets.FloatSlider(min=1.1, max=2.0, step=0.1, value=1.3, description='Severity Factor:')
util_severity_slider = widgets.FloatSlider(min=0, max=100, step=5, value=95, description='GPU/CPU Util Val:')

print("Anomaly Injection Controls (configure then run the cell below):")
display(metric_dropdown)
display(start_time_slider)
display(duration_slider)
display(severity_slider)
display(util_severity_slider)
print("Note: 'Severity Factor' for Temp, Mem, Power. 'Util Val' for GPU/CPU Utilization.\n")

run_button = widgets.Button(description="Generate Data, Train & Evaluate")
output_area = widgets.Output()
global_df = None
TIMESTEPS = 15

def create_sequences(X_data, y_data, time_steps=TIMESTEPS):
    Xs, ys = [], []
    if y_data is None:
        for i in range(len(X_data) - time_steps + 1):
            Xs.append(X_data[i:(i + time_steps)])
        return np.array(Xs), None
    else:
        for i in range(len(X_data) - time_steps +1):
            Xs.append(X_data[i:(i + time_steps)])
            ys.append(y_data[i + time_steps -1])
        return np.array(Xs), np.array(ys)


def on_run_button_clicked(b):
    with output_area:
        clear_output(wait=True)
        print("Starting process...")
        is_util_metric = metric_dropdown.value in ['GPU_Utilization', 'CPU_Utilization']
        user_anomaly_info = {
            'metric': metric_dropdown.value,
            'start_time': start_time_slider.value,
            'duration': duration_slider.value,
            'severity_factor': util_severity_slider.value if is_util_metric else severity_slider.value
        }
        print(f"User-defined anomaly: {user_anomaly_info}")
        global global_df
        global_df = generate_gpu_data(num_samples=10000, anomaly_info=user_anomaly_info)
        print(f"Data generated. Anomalous samples: {global_df['Label'].sum()}/{len(global_df)}")

        print("\nPreprocessing data...")
        features = ['Temperature', 'GPU_Utilization', 'Memory_Utilization', 'Power_Consumption', 'CPU_Utilization']
        X = global_df[features]
        y = global_df['Label']
        X_train_df, X_test_df, y_train_series, y_test_series = train_test_split(X, y, test_size=0.3, random_state=42, stratify=y if y.sum() > 1 else None)
        scaler = StandardScaler()
        X_train_scaled_flat = scaler.fit_transform(X_train_df)
        X_test_scaled_flat = scaler.transform(X_test_df)
        X_train_flat, y_train_flat = X_train_scaled_flat, y_train_series.to_numpy()
        X_test_flat, y_test_flat = X_test_scaled_flat, y_test_series.to_numpy()

        print(f"\nCreating sequences for LSTM (TIMESTEPS={TIMESTEPS})...")
        X_train_seq, y_train_seq = create_sequences(X_train_scaled_flat, y_train_series.to_numpy(), TIMESTEPS)
        X_test_seq, y_test_seq = create_sequences(X_test_scaled_flat, y_test_series.to_numpy(), TIMESTEPS)

        if X_train_seq.shape[0] == 0 or X_test_seq.shape[0] == 0: print("Error: Not enough data for LSTM sequences."); return
        if np.sum(y_train_seq) == 0 or (len(np.unique(y_test_seq)) < 2 and np.sum(y_test_seq) < 1) :
            print("Warning: LSTM train/test sequences have very few/no positive samples.")
        print(f"LSTM input shape (Train): {X_train_seq.shape}")
        print("Data scaled and split.")

        models_performance = {}

        print("\n--- Training Logistic Regression ---")
        lr_model = LogisticRegression(solver='liblinear', random_state=42, class_weight='balanced')
        lr_model.fit(X_train_flat, y_train_flat)
        lr_train_acc = accuracy_score(y_train_flat, lr_model.predict(X_train_flat))
        lr_test_acc = accuracy_score(y_test_flat, lr_model.predict(X_test_flat))
        lr_log_loss = log_loss(y_test_flat, lr_model.predict_proba(X_test_flat))
        models_performance['Logistic Regression'] = {'Train Accuracy': lr_train_acc, 'Test Accuracy': lr_test_acc, 'Test Log Loss': lr_log_loss}
        print(f"Train Acc: {lr_train_acc:.4f}, Test Acc: {lr_test_acc:.4f}, Test Log Loss: {lr_log_loss:.4f}")
        print("Classification Report (LR Test):\n", classification_report(y_test_flat, lr_model.predict(X_test_flat), zero_division=0))

        print("\n--- Training Random Forest ---")
        rf_model = RandomForestClassifier(n_estimators=100, random_state=42, class_weight='balanced', n_jobs=-1)
        rf_model.fit(X_train_flat, y_train_flat)
        rf_train_acc = accuracy_score(y_train_flat, rf_model.predict(X_train_flat))
        rf_test_acc = accuracy_score(y_test_flat, rf_model.predict(X_test_flat))
        models_performance['Random Forest'] = {'Train Accuracy': rf_train_acc, 'Test Accuracy': rf_test_acc}
        print(f"Train Acc: {rf_train_acc:.4f}, Test Acc: {rf_test_acc:.4f}")
        print("Classification Report (RF Test):\n", classification_report(y_test_flat, rf_model.predict(X_test_flat), zero_division=0))

        print("\n--- Training LSTM ---")
        lstm_model = Sequential([
            Input(shape=(TIMESTEPS, X_train_seq.shape[2])),
            LSTM(64, return_sequences=True), Dropout(0.3),
            LSTM(32), Dropout(0.3),
            Dense(16, activation='relu'), Dense(1, activation='sigmoid')
        ])
        lstm_model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=0.001), loss='binary_crossentropy', metrics=['accuracy'])
        neg_l, pos_l = np.bincount(y_train_seq) if len(np.bincount(y_train_seq)) > 1 else (len(y_train_seq),0)
        cw_l = {0: (1/neg_l)*((neg_l+pos_l)/2.0), 1: (1/pos_l)*((neg_l+pos_l)/2.0)} if pos_l > 0 and neg_l > 0 else None
        es = EarlyStopping(monitor='val_loss', patience=10, restore_best_weights=True, verbose=1)
        history = lstm_model.fit(X_train_seq, y_train_seq, epochs=60, batch_size=64,
                               validation_data=(X_test_seq, y_test_seq), verbose=1, callbacks=[es], class_weight=cw_l)
        loss_l, acc_l = lstm_model.evaluate(X_test_seq, y_test_seq, verbose=0)
        lstm_train_acc_hist = history.history['accuracy'][-1] if 'accuracy' in history.history else "N/A"
        models_performance['LSTM'] = {'Train Accuracy': lstm_train_acc_hist, 'Test Accuracy': acc_l, 'Test Loss': loss_l}
        print(f"LSTM Final Train Acc (hist): {lstm_train_acc_hist if isinstance(lstm_train_acc_hist, float) else 'N/A':.4f}, Test Acc: {acc_l:.4f}, Test Loss: {loss_l:.4f}")
        print("Classification Report (LSTM Test):\n", classification_report(y_test_seq, (lstm_model.predict(X_test_seq) > 0.5).astype(int), zero_division=0))

        print("\n--- Model Performance Summary ---")
        perf_df = pd.DataFrame([{ 'Model': mn, **mv } for mn, mv in models_performance.items()])
        print(perf_df.to_string(float_format="%.4f"))
        plt.figure(figsize=(10,6)); sns.barplot(x='Test Accuracy', y='Model', data=perf_df[perf_df['Test Accuracy']!='N/A'].astype({'Test Accuracy': float}).sort_values('Test Accuracy', ascending=False), palette='viridis'); plt.title('Model Test Accuracy Comparison'); plt.xlim(0,1); plt.show()

        if 'LSTM' in models_performance:
            print("\n--- LSTM Training History ---")
            hist = history.history
            plt.figure(figsize=(12,4)); plt.subplot(1,2,1); plt.plot(hist['loss'],label='Train Loss'); plt.plot(hist.get('val_loss'),label='Val Loss'); plt.title('LSTM Loss'); plt.xlabel('Epoch'); plt.ylabel('Loss'); plt.legend()
            plt.subplot(1,2,2); plt.plot(hist['accuracy'],label='Train Acc'); plt.plot(hist.get('val_accuracy'),label='Val Acc'); plt.title('LSTM Accuracy'); plt.xlabel('Epoch'); plt.ylabel('Accuracy'); plt.legend(); plt.tight_layout(); plt.show()

        print("\n--- Visualizing Metric Data and Anomaly Detection (on entire dataset) ---")
        full_X_scaled = scaler.transform(global_df[features])
        global_df['Pred_LR'] = lr_model.predict(full_X_scaled)
        global_df['Pred_RF'] = rf_model.predict(full_X_scaled)
        full_X_seq, _ = create_sequences(full_X_scaled, None, TIMESTEPS)
        if full_X_seq.shape[0]>0: global_df['Pred_LSTM'] = np.concatenate((np.array([0]*(TIMESTEPS-1)), (lstm_model.predict(full_X_seq) > 0.5).astype(int).flatten()))
        else: global_df['Pred_LSTM'] = 0

        user_anomaly_start_time = user_anomaly_info['start_time']
        user_anomaly_duration = user_anomaly_info['duration']
        user_anomaly_end_time = user_anomaly_start_time + user_anomaly_duration

        metrics_to_plot = ['Temperature', 'GPU_Utilization', 'Memory_Utilization', 'Power_Consumption', 'CPU_Utilization']
        for metric_name in metrics_to_plot:
            plt.figure(figsize=(18, 7)) # Full Plot
            plt.plot(global_df['Time'], global_df[metric_name], label=f'Actual {metric_name}', color='deepskyblue', alpha=0.9, lw=1.5)
            true_anom_df = global_df[global_df['Label'] == 1]
            plt.scatter(true_anom_df['Time'], true_anom_df[metric_name], color='red', marker='o', s=35, label='True Anomaly', alpha=0.7, zorder=5)
            plt.axvspan(user_anomaly_start_time, user_anomaly_end_time, color='gold', alpha=0.3, label='User Injected Anomaly')

            rf_det = global_df[(global_df['Pred_RF']==1)&(global_df['Label']==1)]
            plt.scatter(rf_det['Time'], rf_det[metric_name], color='blue', marker='x', s=45, label='RF Detected (Correct)', zorder=3, alpha=0.8)
            lstm_det = global_df[(global_df['Pred_LSTM']==1)&(global_df['Label']==1)]
            plt.scatter(lstm_det['Time'], lstm_det[metric_name], color='green', marker='P', s=50, label='LSTM Detected (Correct)', zorder=4, alpha=0.8)

            # CORRECTED LINES: lbl -> label
            if metric_name == 'Temperature':
                plt.axhline(85,c='coral',ls='--',label='Warning (85°C)')
                plt.axhline(90,c='firebrick',ls='--',label='Critical (90°C)')
            elif metric_name == 'Power_Consumption':
                plt.axhline(250,c='coral',ls='--',label='Typical TDP (250W)')
                plt.axhline(300,c='firebrick',ls='--',label='Max TDP (300W)')
            elif metric_name == 'CPU_Utilization':
                plt.axhline(85, c='coral', ls='--', label='High CPU Load (85%)')

            plt.title(f'{metric_name} - Full Range'); plt.xlabel('Time Step'); plt.ylabel(metric_name); plt.legend(loc='upper left', bbox_to_anchor=(1.02,1)); plt.grid(True,ls=':',alpha=0.7); plt.tight_layout(rect=[0,0,0.85,1]); plt.show()

            # Zoomed-in Plot
            zoom_buffer = max(30, int(user_anomaly_duration * 0.25))
            zoom_start = max(0, user_anomaly_start_time - zoom_buffer)
            zoom_end = min(len(global_df), user_anomaly_end_time + zoom_buffer)
            zoomed_df = global_df[(global_df['Time'] >= zoom_start) & (global_df['Time'] <= zoom_end)]

            if not zoomed_df.empty:
                plt.figure(figsize=(16, 6))
                plt.plot(zoomed_df['Time'], zoomed_df[metric_name], label=f'Actual {metric_name}', color='deepskyblue', lw=2)
                true_anom_zoom = zoomed_df[zoomed_df['Label']==1]
                plt.scatter(true_anom_zoom['Time'], true_anom_zoom[metric_name], color='red', marker='o', s=50, label='True Anomaly', alpha=0.7, zorder=5)
                plt.axvspan(max(zoom_start, user_anomaly_start_time), min(zoom_end, user_anomaly_end_time), color='gold', alpha=0.3, label='User Injected Anomaly')

                rf_det_zoom = zoomed_df[(zoomed_df['Pred_RF']==1)&(zoomed_df['Label']==1)]
                plt.scatter(rf_det_zoom['Time'], rf_det_zoom[metric_name], color='blue', marker='x', s=60, label='RF Detected (Correct)', zorder=3)
                lstm_det_zoom = zoomed_df[(zoomed_df['Pred_LSTM']==1)&(zoomed_df['Label']==1)]
                plt.scatter(lstm_det_zoom['Time'], lstm_det_zoom[metric_name], color='green', marker='P', s=65, label='LSTM Detected (Correct)', zorder=4)

                # CORRECTED LINES: lbl -> label
                if metric_name == 'Temperature':
                    plt.axhline(85,c='coral',ls='--',label='Warning (85°C)')
                    plt.axhline(90,c='firebrick',ls='--',label='Critical (90°C)')
                elif metric_name == 'Power_Consumption':
                    plt.axhline(250,c='coral',ls='--',label='Typical TDP (250W)')
                    plt.axhline(300,c='firebrick',ls='--',label='Max TDP (300W)')
                elif metric_name == 'CPU_Utilization':
                    plt.axhline(85, c='coral', ls='--', label='High CPU Load (85%)')

                plt.title(f'{metric_name} - Zoomed (User Anomaly: {user_anomaly_start_time}-{user_anomaly_end_time})'); plt.xlabel('Time Step'); plt.ylabel(metric_name); plt.legend(loc='upper left', bbox_to_anchor=(1.02,1)); plt.grid(True,ls='-',alpha=0.6); plt.tight_layout(rect=[0,0,0.85,1]); plt.show()

        print("\n--- End of Analysis ---")
        print("Adjust anomaly parameters and click 'Generate Data, Train & Evaluate' to re-run.")

run_button.on_click(on_run_button_clicked)
display(run_button)
display(output_area)

